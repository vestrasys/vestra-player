//! `plugin.app`: the build's git short hash and the linked Slint version.
#![forbid(unsafe_code)]
use std::process::Command;

#[path = "src/i18n/po.rs"]
#[allow(dead_code)]
mod po;
#[path = "windows/resources.rs"]
mod resources;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.lock");
    let lock = std::fs::read_to_string("Cargo.lock").unwrap_or_default();
    let slint = lock
        .split("[[package]]")
        .find(|package| package.contains("\nname = \"slint\"\n"))
        .and_then(|package| {
            package.lines().find_map(|line| {
                Some(
                    line.strip_prefix("version = \"")?
                        .strip_suffix('"')?
                        .to_owned(),
                )
            })
        })
        .unwrap_or_default();
    println!("cargo:rustc-env=VESTRA_SLINT_VERSION={slint}");
    windows_manifest();
    locales();
    let git = |args: &[&str]| {
        Command::new("git")
            .args(args)
            .output()
            .ok()
            .filter(|output| output.status.success())
            .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_owned())
            .filter(|text| !text.is_empty())
    };
    // No git (a source tarball): `build` is null.
    if let Some(directory) = git(&["rev-parse", "--git-dir"]) {
        println!("cargo:rerun-if-changed={directory}/HEAD");
        println!("cargo:rerun-if-changed={directory}/logs/HEAD");
    }
    if let Some(hash) = git(&["rev-parse", "--short", "HEAD"]) {
        println!("cargo:rustc-env=VESTRA_BUILD={hash}");
    }
}

/// Windows (MSVC): embed `windows/vestra.manifest` in every linked binary
/// (the host and its test harness). It turns on Common Controls v6, which
/// rfd's `common-controls-v6` needs to start at all (custom dialog buttons).
fn windows_manifest() {
    println!("cargo:rerun-if-changed=windows/vestra.manifest");
    let var = |key: &str| std::env::var(key).unwrap_or_default();
    if var("CARGO_CFG_TARGET_OS") != "windows" {
        return;
    }
    if var("CARGO_CFG_TARGET_ENV") != "msvc" {
        println!(
            "cargo:warning=no application manifest for this Windows toolchain; dialogs need Common Controls v6"
        );
        return;
    }
    let manifest = std::path::Path::new(&var("CARGO_MANIFEST_DIR")).join("windows/vestra.manifest");
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    windows_resources(&var("CARGO_MANIFEST_DIR"), &var("OUT_DIR"));
}

/// Windows (MSVC): the application icon (`windows/vestra.ico`, generated by
/// `src/packaging/icon.mjs`) and VERSIONINFO, as a `.res` file link.exe
/// embeds. Written by `windows/resources.rs`, so no rc.exe is needed.
fn windows_resources(manifest_dir: &str, out_dir: &str) {
    println!("cargo:rerun-if-changed=windows/vestra.ico");
    println!("cargo:rerun-if-changed=windows/resources.rs");
    let ico = std::fs::read(std::path::Path::new(manifest_dir).join("windows/vestra.ico"))
        .expect("read windows/vestra.ico");
    let version = env!("CARGO_PKG_VERSION");
    let res = resources::resource_file(
        &ico,
        version,
        &[
            ("CompanyName", "Vestra Player contributors"),
            ("FileDescription", "Vestra Player"),
            ("FileVersion", version),
            ("InternalName", "vestra-host"),
            ("LegalCopyright", "GPL-3.0-or-later"),
            ("OriginalFilename", "vestra-host.exe"),
            ("ProductName", "Vestra Player"),
            ("ProductVersion", version),
        ],
    )
    .expect("windows/vestra.ico is a valid icon");
    let path = std::path::Path::new(out_dir).join("vestra.res");
    std::fs::write(&path, res).expect("write vestra.res");
    println!("cargo:rustc-link-arg={}", path.display());
}

/// The player's own catalogs (doc/architecture/i18n.md §6): every
/// `locales/<lang>.po` compiled to `$OUT_DIR/locales/<lang>.json`, and
/// `$OUT_DIR/host_catalogs.rs` listing them all (`HOST_CATALOGS`, included by
/// `src/i18n/mod.rs`), so a new `.po` is embedded without touching the code.
/// A test checks the list matches `i18n::LOCALES`. A broken file fails the
/// build.
fn locales() {
    println!("cargo:rerun-if-changed=locales");
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let out = out_dir.join("locales");
    std::fs::create_dir_all(&out).expect("create OUT_DIR/locales");
    let mut found = Vec::new();
    for entry in std::fs::read_dir("locales").expect("read locales/") {
        let path = entry.expect("locales/ entry").path();
        let Some(language) = path
            .file_name()
            .and_then(|n| n.to_str())
            .and_then(|n| n.strip_suffix(".po"))
        else {
            continue;
        };
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path).expect("read a .po file");
        let entries = po::parse(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        std::fs::write(
            out.join(format!("{language}.json")),
            po::compile(language, &entries),
        )
        .expect("write a compiled catalog");
        found.push(language.to_owned());
    }
    assert!(
        found.iter().any(|l| l == "zh-Hans"),
        "locales/zh-Hans.po is missing"
    );
    found.sort();
    let mut list = String::from("pub const HOST_CATALOGS: &[(&str, &str)] = &[\n");
    for language in &found {
        list.push_str(&format!(
            "    ({language:?}, include_str!(concat!(env!(\"OUT_DIR\"), \"/locales/{language}.json\"))),\n"
        ));
    }
    list.push_str("];\n");
    std::fs::write(out_dir.join("host_catalogs.rs"), list).expect("write host_catalogs.rs");
}
