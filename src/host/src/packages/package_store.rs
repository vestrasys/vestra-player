    /// `quarantine.json`'s records; none when it is missing, unreadable or
    /// larger than `MAX_CATALOG` (it is never written larger).
    fn quarantine_records(&self) -> Vec<Value> {
        let path = self.root.join("quarantine.json");
        let mut bytes = Vec::new();
        let read = File::open(&path)
            .and_then(|file| file.take(MAX_CATALOG as u64 + 1).read_to_end(&mut bytes));
        if read.is_err() {
            return Vec::new();
        }
        if bytes.len() > MAX_CATALOG {
            diag!("package library: {} is too large; not read", path.display());
            return Vec::new();
        }
        serde_json::from_slice::<Value>(&bytes)
            .ok()
            .and_then(|value| value.get("records").and_then(Value::as_array).cloned())
            .unwrap_or_default()
            .into_iter()
            .filter(Value::is_object)
            .collect()
    }

    fn publish(&mut self, next: Catalog) -> Result<()> {
        let bytes = serde_json::to_vec(&next)?;
        ensure!(
            bytes
                .len()
                .checked_add(next.pending.len() * 64 * 1024)
                .is_some_and(|size| size <= MAX_CATALOG),
            "package catalog byte limit or reserved terminal receipt capacity exceeded"
        );
        let mut temporary = tempfile::NamedTempFile::new_in(&self.root)?;
        temporary.write_all(&bytes)?;
        temporary.as_file().sync_all()?;
        temporary
            .persist(self.root.join("catalog.json"))
            .map_err(|error| error.error)?;
        // Publish succeeded even if the directory durability barrier fails:
        // callers must query/recover rather than blindly repeat an operation.
        self.catalog = next;
        self.revision += 1;
        crate::platform::sync_dir(&self.root)?;
        Ok(())
    }

