    /// The installed records `Store::open` set aside, with their reasons.
    fn installed_aside(store: &Store) -> Vec<(String, String)> {
        let mut aside = store
            .quarantined()
            .iter()
            .filter(|q| q.section == "installed")
            .map(|q| (q.id.clone(), q.reason.clone()))
            .collect::<Vec<_>>();
        aside.sort();
        aside
    }

