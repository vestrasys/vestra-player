//! Single-writer package library, not an activation engine.
//! Host owns the sole Store for this root. Journal and installed state share
//! one atomic catalog replacement; recovery never implies a runtime is ready.
#![forbid(unsafe_code)]

use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs::{self, File},
    io::{Read, Write},
    path::PathBuf,
};

use crate::package_stage::{Candidate, PackageManifest};

const MAX_SAFE: u64 = (1_u64 << 53) - 1;
const MAX_CATALOG: usize = 2 * 1024 * 1024;
const MAX_PACKAGES: usize = 128;
/// Operation receipts kept; when full, the oldest finished ones make room.
const MAX_OPERATIONS: usize = 512;
/// Retired instances kept so that a later install from the same source
/// reconnects to their data (see `Dormant`).
pub const MAX_DORMANT: usize = 256;

/// Where an installed instance came from (`PluginInfo.source`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase", deny_unknown_fields)]
pub enum Source {
    /// A repository: the full `index.json` address.
    Repository { url: String },
    /// A package link.
    Link { url: String },
    /// A local package file or directory.
    File,
    /// Generated by the plugin workshop.
    Workshop,
    /// Shipped with the player and run from its installation
    /// (`<resources>/plugins/<id>`).
    Bundled,
}
impl Source {
    /// Installs with the same identity upgrade one another; a different
    /// identity replaces (store proposal §2.3). Links and files are one
    /// manual source.
    pub fn identity(&self) -> String {
        match self {
            Self::Repository { url } => format!("repository {url}"),
            Self::Link { .. } | Self::File => "manual".into(),
            Self::Workshop => "workshop".into(),
            Self::Bundled => "bundled".into(),
        }
    }
}

/// An installation instance: the GUID all local state hangs under.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Instance {
    pub guid: String,
    pub source: Source,
    /// A built-in plugin: runs from the installation (`builtin.json`); can be
    /// disabled, not uninstalled or replaced. Its record has no package.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub builtin: bool,
    /// When this instance was first installed (Unix milliseconds).
    pub installed_at: u64,
    /// Written by players up to 0.5, which copied built-ins into the
    /// library; read so that their catalogs open, cleared by `Store::open`.
    /// An older player that finds it absent copies the built-in again.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seeded_version: Option<String>,
}
impl Instance {
    pub fn new(source: Source) -> Self {
        Self {
            guid: new_guid(),
            source,
            builtin: false,
            installed_at: unix_ms(),
            seeded_version: None,
        }
    }
}

/// A replaced or uninstalled (data kept) instance: only its data remains.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Dormant {
    pub id: String,
    pub source: Source,
    #[serde(default)]
    pub version: Option<String>,
    pub installed_at: u64,
    pub retired_at: u64,
}

pub fn new_guid() -> String {
    uuid::Uuid::new_v4().hyphenated().to_string()
}
fn valid_guid(value: &str) -> bool {
    uuid::Uuid::try_parse(value).is_ok_and(|uuid| uuid.hyphenated().to_string() == value)
}
pub fn unix_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis().min(MAX_SAFE as u128) as u64)
        .unwrap_or(0)
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct StoredPackage {
    pub digest: String,
    pub manifest: PackageManifest,
    pub directory: PathBuf,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Installed {
    pub revision: u64,
    /// The package that runs; `None` for a built-in, which runs from the
    /// installation.
    pub current: Option<StoredPackage>,
    /// Always `None` now: players up to 0.5 kept the replaced version here
    /// so that the user could go back to it. Kept as a field so that those players still read the
    /// catalog (`Installed` refuses unknown and needs known fields).
    pub previous: Option<StoredPackage>,
    /// The current instance (always present while `current` is).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instance: Option<Instance>,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Recovery {
    pub id: String,
    pub operation_id: String,
    pub before: Installed,
    pub target: StoredPackage,
    /// The instance the target installs into; `None` keeps `before`'s.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instance: Option<Instance>,
}

#[derive(Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Catalog {
    installed: BTreeMap<String, Installed>,
    pending: BTreeMap<String, Recovery>,
    operations: BTreeMap<String, Value>,
    /// When each receipt was last written (unix ms), for evicting the
    /// oldest. Receipts from older catalogs have none and go first.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    operation_at: BTreeMap<String, u64>,
    // One successful commit receipt per package makes a lost commit reply
    // retry harmless; full request deduplication belongs to the manager.
    last_commit: BTreeMap<String, String>,
    /// Installed packages the user disabled (R-H10): not started at launch.
    #[serde(default, skip_serializing_if = "BTreeSet::is_empty")]
    disabled: BTreeSet<String>,
    /// Retired instances by GUID (store proposal §1.2).
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    dormant: BTreeMap<String, Dormant>,
    /// Retired instances (GUID, package id) not kept because `dormant` was
    /// full, until the manager takes them (not stored).
    #[serde(skip)]
    dropped: Vec<(String, String)>,
}

pub struct Store {
    root: PathBuf,
    catalog: Catalog,
}

fn identifier(value: &str) -> Result<()> {
    ensure!(
        !value.is_empty()
            && value.len() <= 128
            && value
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"._-".contains(&b)),
        "invalid package or operation identity"
    );
    Ok(())
}

impl Store {
    pub fn open(root: PathBuf) -> Result<Self> {
        fs::create_dir_all(&root)?;
        ensure!(
            !fs::symlink_metadata(&root)?.file_type().is_symlink(),
            "store root must not be a symlink"
        );
        let root = dunce::canonicalize(&root)?;
        fs::create_dir_all(root.join("packages"))?;
        ensure!(
            !fs::symlink_metadata(root.join("packages"))?
                .file_type()
                .is_symlink(),
            "package library must not be a symlink"
        );
        let path = root.join("catalog.json");
        let catalog = if path.exists() {
            let metadata = fs::symlink_metadata(&path)?;
            ensure!(
                metadata.is_file()
                    && !metadata.file_type().is_symlink()
                    && metadata.len() <= MAX_CATALOG as u64,
                "invalid package catalog"
            );
            let mut bytes = Vec::new();
            File::open(path)?
                .take(MAX_CATALOG as u64 + 1)
                .read_to_end(&mut bytes)?;
            ensure!(bytes.len() <= MAX_CATALOG, "package catalog too large");
            serde_json::from_slice(&bytes).context("parse package catalog")?
        } else {
            Catalog::default()
        };
        let mut store = Self { root, catalog };
        store.validate_catalog()?;
        // Catalogs written before instances: give each installed package a
        // fresh instance (its old `plugin-data/<id>` is not migrated).
        let mut next = store.catalog.clone();
        let mut changed = false;
        for (id, installed) in next.installed.iter_mut() {
            if installed.current.is_some() && installed.instance.is_none() {
                let instance = Instance::new(Source::File);
                if let Some(recovery) = next.pending.get_mut(id) {
                    recovery.before.instance = Some(instance.clone());
                }
                installed.instance = Some(instance);
                changed = true;
            }
        }
        changed |= migrate_in_place(&mut next);
        if changed {
            store.publish(next)?;
        }
        Ok(store)
    }

    /// Give each built-in plugin of the installation (`ids`, from
    /// `builtin.json`) a record, in one catalog replacement: a new
    /// instance, or the dormant one of a built-in that comes back. A
    /// built-in record whose id is no longer listed is retired (its data
    /// stays). A record of a listed id installed from another source (from
    /// before ids were reserved) is left alone; it does not start.
    pub fn sync_builtins(&mut self, ids: &BTreeSet<String>) -> Result<()> {
        let mut next = self.catalog.clone();
        let mut changed = false;
        for id in ids {
            identifier(id)?;
            if next.installed.contains_key(id) || next.pending.contains_key(id) {
                continue;
            }
            ensure!(
                next.installed.len() < MAX_PACKAGES,
                "installed package limit reached"
            );
            let dormant = next
                .dormant
                .iter()
                .filter(|(_, d)| d.id == *id && d.source == Source::Bundled)
                .max_by_key(|(_, d)| d.retired_at)
                .map(|(guid, d)| (guid.clone(), d.installed_at));
            let mut instance = Instance {
                builtin: true,
                ..Instance::new(Source::Bundled)
            };
            if let Some((guid, installed_at)) = dormant {
                next.dormant.remove(&guid);
                instance.guid = guid;
                instance.installed_at = installed_at;
            }
            next.installed.insert(
                id.clone(),
                Installed {
                    instance: Some(instance),
                    ..Installed::default()
                },
            );
            changed = true;
        }
        let dropped = next
            .installed
            .iter()
            .filter(|(id, installed)| {
                !ids.contains(*id)
                    && installed.instance.as_ref().is_some_and(|i| i.builtin)
                    && !next.pending.contains_key(*id)
            })
            .map(|(id, _)| id.clone())
            .collect::<Vec<_>>();
        for id in dropped {
            if let Some(installed) = next.installed.remove(&id)
                && let Some(instance) = &installed.instance
            {
                retire(&mut next, &id, instance, &installed);
            }
            next.disabled.remove(&id);
            next.last_commit.remove(&id);
            changed = true;
        }
        if changed {
            self.publish(next)?;
        }
        Ok(())
    }

    fn validate_package(&self, package: &StoredPackage) -> Result<()> {
        identifier(&package.manifest.id)?;
        ensure!(
            package.digest.len() == 64
                && package
                    .digest
                    .bytes()
                    .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
            "invalid package digest"
        );
        ensure!(
            package.directory == self.root.join("packages").join(&package.digest),
            "package directory is outside this library"
        );
        Ok(())
    }

    fn verify_package(&self, package: &StoredPackage) -> Result<()> {
        self.validate_package(package)?;
        verify_stored(package)
    }

    fn validate_catalog(&self) -> Result<()> {
        ensure!(
            self.catalog.installed.len() <= MAX_PACKAGES
                && self.catalog.pending.len() <= 64
                && self.catalog.operations.len() <= MAX_OPERATIONS
                && self.catalog.operation_at.len() <= MAX_OPERATIONS
                && self.catalog.last_commit.len() <= MAX_PACKAGES,
            "package catalog count exceeded"
        );
        for (id, installed) in &self.catalog.installed {
            identifier(id)?;
            ensure!(
                installed.revision <= MAX_SAFE,
                "installed revision exhausted"
            );
            // `previous` (players up to 0.5) is not followed: `Store::open`
            // clears it.
            if let Some(package) = &installed.current {
                self.validate_package(package)?;
                ensure!(
                    package.manifest.id == *id,
                    "installed package identity mismatch"
                );
            }
        }
        for (id, recovery) in &self.catalog.pending {
            identifier(id)?;
            identifier(&recovery.operation_id)?;
            ensure!(
                recovery.id == *id && recovery.target.manifest.id == *id,
                "recovery identity mismatch"
            );
            self.validate_package(&recovery.target)?;
            ensure!(
                serde_json::to_value(&recovery.before)? == serde_json::to_value(self.get(id))?,
                "recovery baseline mismatch"
            );
        }
        for id in self.catalog.operations.keys() {
            identifier(id)?;
        }
        ensure!(
            self.catalog.dormant.len() <= MAX_DORMANT,
            "dormant instance count exceeded"
        );
        let mut guids = BTreeSet::new();
        for installed in self.catalog.installed.values() {
            if let Some(instance) = &installed.instance {
                ensure!(valid_guid(&instance.guid), "invalid instance GUID");
                ensure!(guids.insert(&instance.guid), "duplicate instance GUID");
            }
        }
        for (guid, dormant) in &self.catalog.dormant {
            ensure!(valid_guid(guid), "invalid instance GUID");
            ensure!(guids.insert(guid), "duplicate instance GUID");
            identifier(&dormant.id)?;
        }
        for recovery in self.catalog.pending.values() {
            if let Some(instance) = &recovery.instance {
                ensure!(valid_guid(&instance.guid), "invalid instance GUID");
            }
        }
        for (id, operation) in &self.catalog.last_commit {
            identifier(id)?;
            identifier(operation)?;
        }
        Ok(())
    }

    fn publish(&mut self, next: Catalog) -> Result<()> {
        let bytes = serde_json::to_vec(&next)?;
        ensure!(
            bytes
                .len()
                .checked_add(next.pending.len() * 64 * 1024)
                .is_some_and(|size| size <= MAX_CATALOG),
            "package catalog byte limit or reserved terminal receipt capacity exceeded"
        );
        let mut temporary = tempfile::NamedTempFile::new_in(&self.root)?;
        temporary.write_all(&bytes)?;
        temporary.as_file().sync_all()?;
        temporary
            .persist(self.root.join("catalog.json"))
            .map_err(|error| error.error)?;
        // Publish succeeded even if the directory durability barrier fails:
        // callers must query/recover rather than blindly repeat an operation.
        self.catalog = next;
        crate::platform::sync_dir(&self.root)?;
        Ok(())
    }

    pub fn get(&self, id: &str) -> Installed {
        self.catalog.installed.get(id).cloned().unwrap_or_default()
    }

    pub fn installed(&self) -> BTreeMap<String, Installed> {
        self.catalog.installed.clone()
    }

    pub fn stage(&self, candidate: &Candidate) -> Result<StoredPackage> {
        self.library().stage(candidate)
    }

    /// The package directories (`packages/`), for staging, and for
    /// collecting garbage on another thread while the catalog stays with
    /// the owner.
    pub fn library(&self) -> Library {
        Library {
            packages: self.root.join("packages"),
        }
    }

    /// The library entries the catalog refers to: every installed current
    /// version and every pending target. Anything else in the library is
    /// garbage (`Library::collect`).
    pub fn referenced(&self) -> BTreeSet<String> {
        let mut referenced = BTreeSet::new();
        for installed in self.catalog.installed.values() {
            if let Some(package) = &installed.current {
                referenced.insert(package.digest.clone());
            }
        }
        for recovery in self.catalog.pending.values() {
            referenced.insert(recovery.target.digest.clone());
        }
        referenced
    }

    pub fn prepare(
        &mut self,
        id: &str,
        expected_revision: u64,
        target: &StoredPackage,
        operation_id: &str,
    ) -> Result<()> {
        self.prepare_with_receipt(
            id,
            expected_revision,
            target,
            operation_id,
            serde_json::json!({"operationId":operation_id,"packageId":id,"status":"preparing"}),
            None,
        )
    }

    pub fn prepare_with_receipt(
        &mut self,
        id: &str,
        expected_revision: u64,
        target: &StoredPackage,
        operation_id: &str,
        receipt: Value,
        instance: Option<Instance>,
    ) -> Result<()> {
        identifier(id)?;
        ensure!(target.manifest.id == id, "target identity mismatch");
        self.verify_package(target)?;
        let next = self.prepared(
            &self.catalog,
            id,
            expected_revision,
            target,
            operation_id,
            receipt,
            instance,
        )?;
        self.publish(next)
    }

    /// `catalog` with `target` journaled as `id`'s pending transaction; the
    /// caller verified the target's bytes.
    #[allow(clippy::too_many_arguments)]
    fn prepared(
        &self,
        catalog: &Catalog,
        id: &str,
        expected_revision: u64,
        target: &StoredPackage,
        operation_id: &str,
        receipt: Value,
        instance: Option<Instance>,
    ) -> Result<Catalog> {
        identifier(id)?;
        identifier(operation_id)?;
        check_receipt(&receipt)?;
        if let Some(instance) = &instance {
            ensure!(valid_guid(&instance.guid), "invalid instance GUID");
        }
        ensure!(
            expected_revision < MAX_SAFE,
            "invalid or exhausted revision"
        );
        ensure!(target.manifest.id == id, "target identity mismatch");
        ensure!(
            !catalog.pending.contains_key(id),
            "package transaction already pending"
        );
        ensure!(catalog.pending.len() < 64, "pending package limit reached");
        ensure!(
            catalog.installed.contains_key(id)
                || catalog.installed.len()
                    + catalog
                        .pending
                        .keys()
                        .filter(|key| !catalog.installed.contains_key(*key))
                        .count()
                    < MAX_PACKAGES,
            "installed package limit reached"
        );
        let before = catalog.installed.get(id).cloned().unwrap_or_default();
        ensure!(
            before.revision == expected_revision,
            "installed revision conflict"
        );
        let mut next = catalog.clone();
        next.pending.insert(
            id.into(),
            Recovery {
                id: id.into(),
                operation_id: operation_id.into(),
                before,
                target: target.clone(),
                instance,
            },
        );
        insert_receipt(&mut next, operation_id, receipt)?;
        Ok(next)
    }

    pub fn commit(&mut self, id: &str, operation_id: &str) -> Result<Installed> {
        self.commit_with_receipt(
            id,
            operation_id,
            serde_json::json!({"operationId":operation_id,"packageId":id,"status":"committed"}),
        )
    }

    pub fn commit_with_receipt(
        &mut self,
        id: &str,
        operation_id: &str,
        receipt: Value,
    ) -> Result<Installed> {
        identifier(id)?;
        identifier(operation_id)?;
        if self
            .catalog
            .last_commit
            .get(id)
            .is_some_and(|previous| previous == operation_id)
        {
            return Ok(self.get(id));
        }
        let recovery = self
            .catalog
            .pending
            .get(id)
            .context("package transaction missing")?;
        ensure!(
            recovery.operation_id == operation_id,
            "package operation conflict"
        );
        self.verify_package(&recovery.target)?;
        let (next, installed) = Self::committed(self.catalog.clone(), id, operation_id, receipt)?;
        self.publish(next)?;
        Ok(installed)
    }

    /// `catalog` with `id`'s pending transaction `operation_id` committed;
    /// the caller verified the target's bytes.
    fn committed(
        mut next: Catalog,
        id: &str,
        operation_id: &str,
        mut receipt: Value,
    ) -> Result<(Catalog, Installed)> {
        let recovery = next
            .pending
            .remove(id)
            .context("package transaction missing")?;
        ensure!(
            recovery.operation_id == operation_id,
            "package operation conflict"
        );
        let revision = recovery
            .before
            .revision
            .checked_add(1)
            .filter(|n| *n <= MAX_SAFE)
            .context("installed revision exhausted")?;
        let before = recovery.before;
        let instance = recovery
            .instance
            .or_else(|| before.instance.clone())
            .unwrap_or_else(|| Instance::new(Source::File));
        let replaced = before
            .instance
            .as_ref()
            .filter(|old| old.guid != instance.guid);
        if let Some(old) = replaced {
            retire(&mut next, id, old, &before);
        }
        next.dormant.remove(&instance.guid);
        // The replaced version is not kept (nothing goes back to it): its
        // directory is garbage once this is published.
        let installed = Installed {
            revision,
            current: Some(recovery.target),
            previous: None,
            instance: Some(instance),
        };
        ensure!(receipt.is_object(), "operation receipt must be an object");
        receipt["installed"] = serde_json::to_value(&installed)?;
        check_receipt(&receipt)?;
        insert_receipt(&mut next, operation_id, receipt)?;
        next.installed.insert(id.into(), installed.clone());
        next.last_commit.insert(id.into(), operation_id.into());
        // Installing is asking for the package to run.
        next.disabled.remove(id);
        Ok((next, installed))
    }

    pub fn abort(&mut self, id: &str, operation_id: &str) -> Result<()> {
        self.abort_with_receipt(
            id,
            operation_id,
            serde_json::json!({"operationId":operation_id,"packageId":id,"status":"aborted"}),
        )
    }

    pub fn abort_with_receipt(
        &mut self,
        id: &str,
        operation_id: &str,
        receipt: Value,
    ) -> Result<()> {
        identifier(id)?;
        check_receipt(&receipt)?;
        identifier(operation_id)?;
        let pending = self
            .catalog
            .pending
            .get(id)
            .context("package transaction missing")?;
        ensure!(
            pending.operation_id == operation_id,
            "package operation conflict"
        );
        let mut next = self.catalog.clone();
        next.pending.remove(id);
        insert_receipt(&mut next, operation_id, receipt)?;
        self.publish(next)
    }

    pub fn pending(&self) -> Vec<Recovery> {
        self.catalog.pending.values().cloned().collect()
    }

    pub fn save_operation(&mut self, id: &str, value: &Value) -> Result<()> {
        identifier(id)?;
        check_receipt(value)?;
        let mut next = self.catalog.clone();
        insert_receipt(&mut next, id, value.clone())?;
        self.publish(next)
    }

    /// Instances dropped instead of retired since the last call (`retire`).
    pub fn take_dropped(&mut self) -> Vec<(String, String)> {
        std::mem::take(&mut self.catalog.dropped)
    }

    pub fn operations(&self) -> BTreeMap<String, Value> {
        self.catalog.operations.clone()
    }

    pub fn disabled(&self) -> &BTreeSet<String> {
        &self.catalog.disabled
    }

    /// Record whether an installed package stays stopped across launches.
    pub fn set_disabled(&mut self, id: &str, disabled: bool) -> Result<()> {
        identifier(id)?;
        ensure!(
            !disabled || self.catalog.installed.contains_key(id),
            "only installed packages can be disabled"
        );
        if self.catalog.disabled.contains(id) == disabled {
            return Ok(());
        }
        let mut next = self.catalog.clone();
        if disabled {
            next.disabled.insert(id.into());
        } else {
            next.disabled.remove(id);
        }
        self.publish(next)
    }

    /// Remove an installed package in one catalog replacement with its
    /// receipt. Its files are garbage then; the owner collects them off the
    /// UI thread (`Library::collect`). `keep_data` retires the instance
    /// (dormant) so that installing from the same source reconnects to its
    /// data.
    pub fn uninstall(
        &mut self,
        id: &str,
        operation_id: &str,
        receipt: Value,
        keep_data: bool,
    ) -> Result<()> {
        identifier(id)?;
        identifier(operation_id)?;
        check_receipt(&receipt)?;
        ensure!(
            self.catalog.installed.contains_key(id),
            "package is not installed"
        );
        ensure!(
            !self.catalog.pending.contains_key(id),
            "package transaction already pending"
        );
        let mut next = self.catalog.clone();
        if let Some(installed) = next.installed.remove(id)
            && keep_data
            && let Some(instance) = &installed.instance
        {
            retire(&mut next, id, instance, &installed);
        }
        next.disabled.remove(id);
        next.last_commit.remove(id);
        insert_receipt(&mut next, operation_id, receipt)?;
        self.publish(next)
    }
}

impl Store {
    /// A dormant instance of `id` whose source has `identity`.
    pub fn dormant_match(&self, id: &str, identity: &str) -> Option<(String, Dormant)> {
        self.catalog
            .dormant
            .iter()
            .filter(|(_, d)| d.id == id && d.source.identity() == identity)
            .max_by_key(|(_, d)| d.retired_at)
            .map(|(guid, d)| (guid.clone(), d.clone()))
    }

    pub fn dormant(&self) -> &BTreeMap<String, Dormant> {
        &self.catalog.dormant
    }

    /// Forget a dormant instance (its data is being deleted).
    pub fn forget_dormant(&mut self, guid: &str) -> Result<()> {
        if !self.catalog.dormant.contains_key(guid) {
            return Ok(());
        }
        let mut next = self.catalog.clone();
        next.dormant.remove(guid);
        self.publish(next)
    }
}

/// Players up to 0.5 copied each built-in into the library ("seeding") and
/// kept the version an upgrade replaced. Built-ins now run from the
/// installation and no previous version is kept: built-in records lose
/// their package, every record its previous version, and an interrupted
/// seed (a pending built-in install) is dropped. Reads no package file;
/// the directories no longer referenced are collected off the UI thread.
/// Idempotent; `true` when it changed `catalog`.
fn migrate_in_place(catalog: &mut Catalog) -> bool {
    let mut changed = false;
    let builtin = |installed: &Installed| installed.instance.as_ref().is_some_and(|i| i.builtin);
    let seeds = catalog
        .pending
        .iter()
        .filter(|(_, recovery)| {
            builtin(&recovery.before) || recovery.instance.as_ref().is_some_and(|i| i.builtin)
        })
        .map(|(id, recovery)| (id.clone(), recovery.operation_id.clone()))
        .collect::<Vec<_>>();
    for (id, operation) in seeds {
        catalog.pending.remove(&id);
        if let Some(receipt) = catalog.operations.get_mut(&operation)
            && receipt.is_object()
        {
            receipt["status"] = "cancelled".into();
            receipt["message"] = "built-in plugins run from the installation".into();
        }
        changed = true;
    }
    for (id, installed) in catalog.installed.iter_mut() {
        if builtin(installed) {
            if installed.current.is_some() {
                installed.current = None;
                changed = true;
            }
            if catalog.last_commit.remove(id).is_some() {
                changed = true;
            }
            if let Some(instance) = installed.instance.as_mut()
                && instance.seeded_version.take().is_some()
            {
                changed = true;
            }
        }
        if installed.previous.take().is_some() {
            changed = true;
        }
    }
    // A pending install's baseline is the installed record as it stands.
    for recovery in catalog.pending.values_mut() {
        if recovery.before.previous.take().is_some() {
            changed = true;
        }
    }
    changed
}

/// Move a replaced or uninstalled instance to the dormant list. When the list
/// is full the record is dropped (its data directory stays on disk).
fn retire(catalog: &mut Catalog, id: &str, instance: &Instance, installed: &Installed) {
    if catalog.dormant.len() >= MAX_DORMANT {
        eprintln!(
            "package library: dormant list full; {id} instance {} is no longer reconnectable",
            instance.guid
        );
        catalog.dropped.push((instance.guid.clone(), id.into()));
        return;
    }
    catalog.dormant.insert(
        instance.guid.clone(),
        Dormant {
            id: id.into(),
            source: instance.source.clone(),
            version: installed
                .current
                .as_ref()
                .and_then(|c| c.manifest.version.clone()),
            installed_at: instance.installed_at,
            retired_at: unix_ms(),
        },
    );
}

fn check_receipt(value: &Value) -> Result<()> {
    ensure!(
        value.is_object() && serde_json::to_vec(value)?.len() <= 64 * 1024,
        "operation receipt must be an object within 64KiB"
    );
    Ok(())
}

fn insert_receipt(catalog: &mut Catalog, id: &str, value: Value) -> Result<()> {
    if !catalog.operations.contains_key(id) && catalog.operations.len() >= MAX_OPERATIONS {
        evict_receipt(catalog);
    }
    ensure!(
        catalog.operations.contains_key(id) || catalog.operations.len() < MAX_OPERATIONS,
        "operation history capacity reached; existing operations remain queryable"
    );
    catalog.operations.insert(id.into(), value);
    catalog.operation_at.insert(id.into(), unix_ms());
    Ok(())
}

/// Drops the oldest receipt of a finished operation. Kept: operations still
/// in progress (`preparing`, `restoring`, `pending`), the ones a pending
/// transaction belongs to, and each package's last commit (so a lost commit
/// reply can still be looked up).
fn evict_receipt(catalog: &mut Catalog) {
    let live = |id: &String, receipt: &Value| {
        matches!(
            receipt["status"].as_str(),
            Some("preparing" | "restoring" | "pending")
        ) || catalog.pending.values().any(|r| &r.operation_id == id)
            || catalog.last_commit.values().any(|op| op == id)
    };
    let oldest = catalog
        .operations
        .iter()
        .filter(|(id, receipt)| !live(id, receipt))
        .map(|(id, _)| (catalog.operation_at.get(id).copied().unwrap_or(0), id))
        .min()
        .map(|(_, id)| id.clone());
    if let Some(id) = oldest {
        catalog.operations.remove(&id);
        catalog.operation_at.remove(&id);
    }
}

/// Whether a library directory still holds exactly `package` (read in
/// place, `package_stage::inspect`).
fn verify_stored(package: &StoredPackage) -> Result<()> {
    let (digest, manifest) = crate::package_stage::inspect(&package.directory)?;
    ensure!(
        digest == package.digest
            && serde_json::to_value(&manifest)? == serde_json::to_value(&package.manifest)?,
        "stored package bytes or manifest changed"
    );
    Ok(())
}

/// The package directories of a store (`<root>/packages/<digest>`). Staging
/// and garbage collection need no catalog, so they can run on another
/// thread; the store's owner keeps them from running at the same time
/// (`library-cleanup` in `package_manager.rs`: installs and uninstalls
/// answer `busy` meanwhile).
#[derive(Clone, Debug)]
pub struct Library {
    packages: PathBuf,
}

impl Library {
    fn target(&self, digest: &str, manifest: PackageManifest) -> StoredPackage {
        StoredPackage {
            directory: self.packages.join(digest),
            digest: digest.into(),
            manifest,
        }
    }

    /// Copy a validated candidate into the library (if it is not there yet)
    /// and verify the copy.
    pub fn stage(&self, candidate: &Candidate) -> Result<StoredPackage> {
        let target = self.target(candidate.digest(), candidate.manifest().clone());
        if target.directory.exists() {
            verify_stored(&target)?;
            return Ok(target);
        }
        // Capture into a fresh bounded private tree before copying. The public
        // Candidate path is not an OS-immutable filesystem object.
        let source = Candidate::capture(candidate.directory())?;
        ensure!(
            source.digest() == candidate.digest(),
            "candidate bytes changed"
        );
        let temporary = tempfile::Builder::new()
            .prefix(".stage-")
            .tempdir_in(&self.packages)?;
        copy_tree(source.directory(), temporary.path())?;
        let (digest, _) = crate::package_stage::inspect(temporary.path())?;
        ensure!(
            digest == candidate.digest(),
            "candidate changed during staging"
        );
        fs::rename(temporary.path(), &target.directory)?;
        crate::platform::sync_dir(&self.packages)?;
        Ok(target)
    }

    /// Remove the library entries not in `referenced`: old versions,
    /// uninstalled packages, the built-in copies of players up to 0.5, and
    /// leftover `.stage-` / `.trash-` directories. Each is first renamed to
    /// `.trash-<name>`, so that a half-deleted package never sits under a
    /// digest, then deleted. An entry that cannot be removed (a file held
    /// open, for example by an antivirus) is left for the next run. Only
    /// while nothing stages: an entry staged but not yet journaled is not
    /// referenced. Slow on Windows; the host runs it on its
    /// `library-cleanup` thread. Returns how many entries were removed.
    pub fn collect(&self, referenced: &BTreeSet<String>) -> Result<usize> {
        let mut names = Vec::new();
        for entry in fs::read_dir(&self.packages)? {
            let name = entry?.file_name();
            let Some(name) = name.to_str() else {
                continue;
            };
            let leftover = name.starts_with(".stage-") || name.starts_with(".trash-");
            if (digest_name(name) || leftover) && !referenced.contains(name) {
                names.push(name.to_owned());
            }
        }
        self.delete(names)
    }

    /// Remove the library entries `digests` (that the catalog no longer
    /// refers to) the way `collect` does; a missing one is not an error.
    /// Only while nothing stages any of them.
    pub fn remove(&self, digests: &BTreeSet<String>) -> Result<usize> {
        let names = digests
            .iter()
            .filter(|digest| digest_name(digest) && self.packages.join(digest).exists())
            .cloned()
            .collect();
        self.delete(names)
    }

    fn delete(&self, names: Vec<String>) -> Result<usize> {
        let mut removed = 0;
        let mut failures = Vec::new();
        for name in names {
            let path = self.packages.join(&name);
            let metadata = fs::symlink_metadata(&path)?;
            if !metadata.is_dir() || metadata.file_type().is_symlink() {
                failures.push(format!("{name}: not a directory"));
                continue;
            }
            let trash = if name.starts_with('.') {
                path
            } else {
                let trash = self.packages.join(format!(".trash-{name}"));
                if trash.exists() {
                    // From an earlier run that could not finish.
                    let _ = fs::remove_dir_all(&trash);
                }
                if let Err(error) = fs::rename(&path, &trash) {
                    failures.push(format!("{name}: {error}"));
                    continue;
                }
                trash
            };
            match fs::remove_dir_all(&trash) {
                Ok(()) => removed += 1,
                Err(error) => failures.push(format!("{name}: {error}")),
            }
        }
        crate::platform::sync_dir(&self.packages)?;
        ensure!(
            failures.is_empty(),
            "{} left for the next run: {}",
            failures.len(),
            failures.join("; ")
        );
        Ok(removed)
    }
}

/// A library entry named after a package digest (64 lowercase hex digits).
fn digest_name(name: &str) -> bool {
    name.len() == 64
        && name
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

fn copy_tree(source: &std::path::Path, destination: &std::path::Path) -> Result<()> {
    for entry in fs::read_dir(source)? {
        let entry = entry?;
        let metadata = fs::symlink_metadata(entry.path())?;
        ensure!(
            !metadata.file_type().is_symlink(),
            "staged symlink rejected"
        );
        let target = destination.join(entry.file_name());
        if metadata.is_dir() {
            fs::create_dir(&target)?;
            copy_tree(&entry.path(), &target)?;
        } else {
            ensure!(metadata.is_file(), "staged special file rejected");
            let mut input = File::open(entry.path())?;
            let mut output = fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(target)?;
            let copied = std::io::copy(&mut (&mut input).take(32 * 1024 * 1024 + 1), &mut output)?;
            ensure!(copied <= 32 * 1024 * 1024, "staged file size exceeded");
            output.sync_all()?;
        }
    }
    crate::platform::sync_dir(destination)?;
    Ok(())
}

