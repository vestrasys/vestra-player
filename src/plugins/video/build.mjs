import {spawn} from 'node:child_process';
import {readFile,writeFile,mkdir,copyFile,cp,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const version=process.argv[2]??'1.0.1';
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)||version.split('.').some(p=>BigInt(p)>4294967295n))throw Error('Version requires three u32 components without leading zeros');
const scratch=path.join(root,'.build');const input=path.join(scratch,'src/plugins/video');
await mkdir(input,{recursive:true});
await writeFile(path.join(scratch,'package.json'),JSON.stringify({type:'module'})+'\n');
const sdk=process.env.VESTRA_SDK_DIR??path.resolve(root,'../../sdk');
await cp(sdk,path.join(scratch,'src/sdk'),{recursive:true});
for(const f of ['main.ts','model.ts'])await copyFile(path.join(root,f),path.join(input,f));
const tsc=process.env.VESTRA_TSC??path.resolve(root,'../../node_modules/typescript/lib/_tsc.js');
const args=[tsc,'--target','ES2022','--module','NodeNext','--moduleResolution','NodeNext','--lib','ES2023,DOM','--strict','--skipLibCheck','--erasableSyntaxOnly','--rewriteRelativeImportExtensions','--rootDir',path.join(scratch,'src'),'--outDir',path.join(scratch,'out'),path.join(input,'main.ts'),path.join(input,'model.ts')];
if(process.env.VESTRA_TYPE_ROOTS)args.push('--typeRoots',process.env.VESTRA_TYPE_ROOTS);
const child=spawn(process.execPath,args,{stdio:'inherit'});
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});
if(code!==0)throw Error(`Compiler exited ${code}`);
const out=path.join(root,'dist');await mkdir(out,{recursive:true});
await writeFile(path.join(out,'package.json'),JSON.stringify({type:'module'})+'\n');
for(const f of ['main.js','model.js'])await copyFile(path.join(scratch,'out/plugins/video',f),path.join(out,f));
await copyFile(path.join(root,'picture.slint'),path.join(out,'picture.slint'));
const manifest=JSON.parse(await readFile(path.join(root,'manifest.json'),'utf8'));
await writeFile(path.join(out,'manifest.json'),JSON.stringify({...manifest,entry:'main.js',version},null,2)+'\n');
await rm(scratch,{recursive:true,force:true});console.log(`Built ${out} version ${version}`);
